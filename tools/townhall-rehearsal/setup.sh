#!/usr/bin/env bash
# Sets up the Town Hall rehearsal network (TH7): a throwaway WordPress multisite on
# http://localhost:8090 with the family site at http://localhost:8090/doit/.
#
#   docker compose -f tools/townhall-rehearsal/docker-compose.yml up -d
#   tools/townhall-rehearsal/setup.sh
#
# Idempotent: every step checks before it changes anything, so a second run changes nothing.
# Generated passwords go to .rehearsal-credentials (gitignored) and are never printed.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
COMPOSE=(docker compose -f "$HERE/docker-compose.yml")
CREDS="$HERE/.rehearsal-credentials"

NETWORK_URL="http://localhost:8090"
NETWORK_DOMAIN="localhost:8090"
SITE_SLUG="doit"
SITE_URL="$NETWORK_URL/$SITE_SLUG"
ADMIN_USER="rehearsal-admin"
ADMIN_EMAIL="rehearsal-admin@rehearsal.test"
PARENT_USER="famparent"
PARENT_EMAIL="famparent@rehearsal.test"
PLUGINS=(xophz-compass xophz-compass-xp xophz-compass-bulletin-board xophz-compass-bugnet)

say() { printf '%s\n' "$*"; }

# One WP-CLI call in the throwaway wpcli container (same volume and plugins as the site).
wp() { "${COMPOSE[@]}" run --rm -T --no-deps wpcli wp "$@"; }

# Write stdin to a file in the web root only when the content differs (as the web server's user).
put_file() {
  local path="$1" tmp
  tmp="$(mktemp)"
  cat > "$tmp"
  if "${COMPOSE[@]}" exec -T -u www-data wordpress cat "$path" 2> /dev/null | cmp -s - "$tmp"; then
    rm -f "$tmp"
    say "  ok      $path"
    return 0
  fi
  "${COMPOSE[@]}" exec -T -u www-data wordpress sh -c "mkdir -p \"\$(dirname '$path')\" && cat > '$path'" < "$tmp"
  rm -f "$tmp"
  say "  wrote   $path"
}

# --- 0. The containers must be up ------------------------------------------------------------
for service in db wordpress; do
  if [ -z "$("${COMPOSE[@]}" ps --status running --quiet "$service")" ]; then
    say "The $service container is not running. Start the network first:"
    say "  docker compose -f tools/townhall-rehearsal/docker-compose.yml up -d"
    exit 1
  fi
done

say "Waiting for WordPress to write its config and for the database to answer..."
ready=0
for _ in $(seq 1 120); do
  if "${COMPOSE[@]}" exec -T wordpress test -f /var/www/html/wp-config.php 2> /dev/null \
    && wp db query "SELECT 1" > /dev/null 2>&1; then
    ready=1
    break
  fi
  sleep 5
done
if [ "$ready" != 1 ]; then
  say "WordPress or the database did not become ready in 10 minutes. Check:"
  say "  docker compose -f tools/townhall-rehearsal/docker-compose.yml logs"
  exit 1
fi

# --- 1. Credentials (generated once, kept in the gitignored file) ----------------------------
FRESH_CREDS=0
if [ -f "$CREDS" ]; then
  # shellcheck disable=SC1090
  . "$CREDS"
else
  FRESH_CREDS=1
  umask 077
  {
    say "# Generated by setup.sh for the throwaway Town Hall rehearsal network. Never commit."
    say "SITE_URL='$SITE_URL'"
    say "NETWORK_ADMIN_USER='$ADMIN_USER'"
    say "NETWORK_ADMIN_PASSWORD='$(openssl rand -base64 18)'"
    say "FAMPARENT_USER='$PARENT_USER'"
    say "FAMPARENT_PASSWORD='$(openssl rand -base64 18)'"
  } > "$CREDS"
  . "$CREDS"
fi
chmod 600 "$CREDS"
say "Credentials: $CREDS"

# --- 2. The network --------------------------------------------------------------------------
if [ -z "$(wp db query "SHOW TABLES LIKE 'wp\\_site'" --skip-column-names)" ]; then
  say "Installing the multisite network (subdirectory) at $NETWORK_URL ..."
  wp core multisite-install --url="$NETWORK_URL" --title="Do It For The XP (rehearsal)" \
    --admin_user="$NETWORK_ADMIN_USER" --admin_password="$NETWORK_ADMIN_PASSWORD" \
    --admin_email="$ADMIN_EMAIL" --skip-email --skip-config
else
  say "  ok      the network is installed"
fi

# The multisite constants (MULTISITE last, so it doubles as the "all set" marker).
if ! wp config has MULTISITE > /dev/null 2>&1; then
  say "Adding the multisite constants to wp-config.php ..."
  wp config set SUBDOMAIN_INSTALL false --raw --type=constant
  wp config set DOMAIN_CURRENT_SITE "$NETWORK_DOMAIN" --type=constant
  wp config set PATH_CURRENT_SITE "/" --type=constant
  wp config set SITE_ID_CURRENT_SITE 1 --raw --type=constant
  wp config set BLOG_ID_CURRENT_SITE 1 --raw --type=constant
  wp config set MULTISITE true --raw --type=constant
else
  say "  ok      the multisite constants are in wp-config.php"
fi

# Subdirectory multisite rewrite rules for Apache (mod_rewrite). The first rule passes the
# Authorization header through, which Application Passwords (Basic auth) need.
put_file /var/www/html/.htaccess << 'HTACCESS'
# BEGIN WordPress Multisite (townhall-rehearsal)
RewriteEngine On
RewriteRule .* - [E=HTTP_AUTHORIZATION:%{HTTP:Authorization}]
RewriteBase /
RewriteRule ^index\.php$ - [L]

# add a trailing slash to /wp-admin
RewriteRule ^([_0-9a-zA-Z-]+/)?wp-admin$ $1wp-admin/ [R=301,L]

RewriteCond %{REQUEST_FILENAME} -f [OR]
RewriteCond %{REQUEST_FILENAME} -d
RewriteRule ^ - [L]
RewriteRule ^([_0-9a-zA-Z-]+/)?(wp-(content|admin|includes).*) $2 [L]
RewriteRule ^([_0-9a-zA-Z-]+/)?(.*\.php)$ $2 [L]
RewriteRule . index.php [L]
# END WordPress Multisite (townhall-rehearsal)
HTACCESS

# Registration: "user accounts" (people can sign up for an account, not for a site).
if [ "$(wp site option get registration --url="$NETWORK_URL" 2> /dev/null || true)" != "user" ]; then
  say "Setting network registration to user accounts ..."
  wp site option update registration user --url="$NETWORK_URL"
else
  say "  ok      registration is user accounts"
fi

# --- 3. The Town Hall's own addition: the site list filter (an mu-plugin) --------------------
# Written before the plugins are activated, so the XP plugin sees /doit as a family site.
put_file /var/www/html/wp-content/mu-plugins/townhall-rehearsal.php << 'MUPLUGIN'
<?php
/**
 * Plugin Name: Town Hall rehearsal
 * Description: Adds the rehearsal site to the Town Hall's family site list (throwaway network only).
 */

add_filter( 'xp_town_hall_site_urls', function ( $urls ) {
  $urls = is_array( $urls ) ? $urls : [];
  $urls[] = 'http://localhost:8090/doit';

  return array_values( array_unique( $urls ) );
} );
MUPLUGIN

# --- 4. The family site ----------------------------------------------------------------------
if ! wp site list --field=url --url="$NETWORK_URL" | grep -Fxq "$SITE_URL/"; then
  say "Creating the site $SITE_URL/ ..."
  wp site create --slug="$SITE_SLUG" --title="Do It For The XP" --email="$ADMIN_EMAIL" --url="$NETWORK_URL"
else
  say "  ok      the site $SITE_URL/ exists"
fi

# Plugins, in dependency order: the parent COMPASS plugin first.
for plugin in "${PLUGINS[@]}"; do
  if wp plugin is-active "$plugin" --url="$SITE_URL" > /dev/null 2>&1; then
    say "  ok      $plugin is active on /$SITE_SLUG/"
  else
    say "Activating $plugin on /$SITE_SLUG/ ..."
    if ! wp plugin activate "$plugin" --url="$SITE_URL"; then
      say "Could not activate $plugin. Record the error above in README.md and stop."
      exit 1
    fi
  fi
done

# --- 5. Content on the family site -----------------------------------------------------------
PATCH_CATEGORY_ID="$(wp term list category --slug=patch-notes --field=term_id --url="$SITE_URL")"
if [ -z "$PATCH_CATEGORY_ID" ]; then
  say "Creating the Patch Notes category ..."
  PATCH_CATEGORY_ID="$(wp term create category "Patch Notes" --slug=patch-notes --porcelain --url="$SITE_URL")"
else
  say "  ok      the patch-notes category exists"
fi

# The sample post WordPress makes with a new site would be a second "news" item.
SAMPLE_POST_ID="$(wp post list --post_type=post --name=hello-world --post_status=any --field=ID --url="$SITE_URL")"
if [ -n "$SAMPLE_POST_ID" ]; then
  say "Removing the sample post ..."
  wp post delete "$SAMPLE_POST_ID" --force --url="$SITE_URL"
fi

ensure_post() { # ensure_post <slug> <title> <content> [category id]
  local slug="$1" title="$2" content="$3" category="${4:-}"
  if [ -n "$(wp post list --post_type=post --name="$slug" --post_status=any --field=ID --url="$SITE_URL")" ]; then
    say "  ok      the post $slug exists"
    return 0
  fi
  say "Creating the post $slug ..."
  if [ -n "$category" ]; then
    wp post create --post_type=post --post_status=publish --post_name="$slug" --post_title="$title" \
      --post_content="$content" --post_category="$category" --porcelain --url="$SITE_URL" > /dev/null
  else
    wp post create --post_type=post --post_status=publish --post_name="$slug" --post_title="$title" \
      --post_content="$content" --porcelain --url="$SITE_URL" > /dev/null
  fi
}

ensure_post "patch-1-rehearsal-hall" "Patch 1: the rehearsal Town Hall opens" \
  "The Town Hall now has a rehearsal site. Quests, news and the suggestion boxes all work here, and nothing you post here reaches the real town." \
  "$PATCH_CATEGORY_ID"
ensure_post "rehearsal-town-news" "Town news: the rehearsal hall is open" \
  "Welcome, heroes. This is the practice town: say hello on the boards and watch the news arrive."

# --- 6. Users --------------------------------------------------------------------------------
# A fresh credentials file next to an existing network (the file was deleted): re-key the admin.
if [ "$FRESH_CREDS" = 1 ] && wp user get "$NETWORK_ADMIN_USER" --field=ID --url="$NETWORK_URL" > /dev/null 2>&1; then
  say "Re-keying the network admin to the new credentials ..."
  wp user update "$NETWORK_ADMIN_USER" --user_pass="$NETWORK_ADMIN_PASSWORD" --skip-email --url="$NETWORK_URL" > /dev/null
fi

if wp user get "$FAMPARENT_USER" --field=ID --url="$NETWORK_URL" > /dev/null 2>&1; then
  if [ "$FRESH_CREDS" = 1 ]; then
    say "Re-keying $FAMPARENT_USER to the new credentials ..."
    wp user update "$FAMPARENT_USER" --user_pass="$FAMPARENT_PASSWORD" --skip-email --url="$NETWORK_URL" > /dev/null
  else
    say "  ok      the user $FAMPARENT_USER exists"
  fi
else
  say "Creating the user $FAMPARENT_USER ..."
  wp user create "$FAMPARENT_USER" "$PARENT_EMAIL" --user_pass="$FAMPARENT_PASSWORD" --role=subscriber \
    --porcelain --url="$NETWORK_URL" > /dev/null
fi

# The parent is a network user and a member of no site: the app adds them to /doit/ as a
# contributor when they link. (remove-role on each site where they hold a role.)
for url in "$NETWORK_URL" "$SITE_URL"; do
  if [ -n "$(wp user get "$FAMPARENT_USER" --field=roles --url="$url")" ]; then
    say "Removing $FAMPARENT_USER's role on $url ..."
    wp user remove-role "$FAMPARENT_USER" --url="$url"
  fi
done

MEMBER_OF="$(wp eval 'echo count( get_blogs_of_user( get_user_by( "login", "'"$FAMPARENT_USER"'" )->ID ) );' --url="$NETWORK_URL")"
if [ "$MEMBER_OF" != "0" ]; then
  say "$FAMPARENT_USER is still a member of $MEMBER_OF site(s); expected none."
  exit 1
fi

# --- 7. Make sure the site answers (and the first request installs the family tables) -------
wp rewrite flush --url="$SITE_URL" > /dev/null 2>&1 || true
status="$(curl -s -o /dev/null -w '%{http_code}' "$SITE_URL/wp-json/" || true)"
say ""
say "The rehearsal network is set up."
say "  site:        $SITE_URL/   (REST index: HTTP $status)"
say "  credentials: $CREDS"
say "  app:         localStorage.setItem(\"xp:townHallSite\", \"$SITE_URL\")"
